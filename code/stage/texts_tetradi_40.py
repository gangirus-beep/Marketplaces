def design(nm):
    m=re.search(r'"([^"]+)"',nm)
    if m: d=m.group(1).strip()
    else:
        parts=[p.strip() for p in re.split(r',\s*',nm) if p.strip()]
        d=[p for p in parts if not re.fullmatch(r'[\dA-Za-zА-Яа-я_]*\d{5,}[\dA-Za-zА-Яа-я_]*',p)][-1]
    if d in DN: return DN[d]
    d=d.replace('_',' ')
    ws=[]
    for i,w in enumerate(d.split()):
        if re.fullmatch(r'[A-Z&\-]{2,}',w): w='-'.join(p.capitalize() for p in w.split('-'))          # INDAY → Inday
        elif re.fullmatch(r'[А-ЯЁ\-]+',w): w=w.lower()                                             # ПРИРОДА → природа
        ws.append(w)
    d=' '.join(ws)
    return d[0].upper()+d[1:]
